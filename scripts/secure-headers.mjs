// Post-build step: write the security headers for the static site into dist/_headers.
//
// The Content-Security-Policy is generated from the built HTML so that every inline script Astro
// emits is allowed by its SHA-256 hash while everything else is blocked. If a new inline script
// appears, the next build includes its hash automatically; if a page needs a new third-party host,
// it must be added to `allowedHosts` below (audit-build.mjs fails otherwise).
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const turnstileHost = 'https://challenges.cloudflare.com';

export function inlineScriptHashes(htmlDocuments) {
  const hashes = new Set();
  for (const html of htmlDocuments) {
    for (const [, attributes, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
      if (/\bsrc=/.test(attributes) || /type="application\/ld\+json"/.test(attributes) || !body.trim()) continue;
      hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`);
    }
  }
  return [...hashes].sort();
}

export function contentSecurityPolicy(hashes) {
  return [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')} ${turnstileHost}`.replace(/ {2,}/g, ' '),
    // Astro emits scoped <style> blocks and style="" attributes; styles cannot run script.
    "style-src 'self' 'unsafe-inline'",
    // Product photos from the live shop feed are https-only images.
    "img-src 'self' data: https:",
    "font-src 'self'",
    "media-src 'self'",
    `connect-src 'self' ${turnstileHost}`,
    `frame-src ${turnstileHost}`,
    "form-action 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'self'",
    'upgrade-insecure-requests',
  ].join('; ');
}

export const permissionsPolicy = ['accelerometer', 'camera', 'geolocation', 'gyroscope', 'magnetometer', 'microphone', 'payment', 'usb'].map(name => `${name}=()`).join(', ');

export function headerBlock(csp) {
  return [
    '',
    '/*',
    `  Content-Security-Policy: ${csp}`,
    '  Strict-Transport-Security: max-age=31536000',
    `  Permissions-Policy: ${permissionsPolicy}`,
    '  Cross-Origin-Opener-Policy: same-origin',
    '  X-Permitted-Cross-Domain-Policies: none',
    '',
    // Content-hashed build output never changes under the same URL.
    '/_astro/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '/fonts/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ].join('\n');
}

async function htmlFiles(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...await htmlFiles(path));
    else if (entry.name.endsWith('.html')) found.push(path);
  }
  return found;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dist = fileURLToPath(new URL('../dist/', import.meta.url));
  const documents = await Promise.all((await htmlFiles(dist)).map(file => readFile(file, 'utf8')));
  const headersPath = join(dist, '_headers');
  const existing = (await readFile(headersPath, 'utf8')).replace(/\n# --- generated by scripts\/secure-headers\.mjs[\s\S]*$/, '').trimEnd();
  // The static rules in public/_headers stay; the generated block is appended after a marker so reruns are idempotent.
  const csp = contentSecurityPolicy(inlineScriptHashes(documents));
  await writeFile(headersPath, `${existing}\n\n# --- generated by scripts/secure-headers.mjs (do not edit; edit the script) ---${headerBlock(csp)}`);
  console.log(`Security headers written: ${inlineScriptHashes(documents).length} inline script hashes across ${documents.length} pages.`);
}
